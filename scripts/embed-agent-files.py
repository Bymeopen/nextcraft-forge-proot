#!/usr/bin/env python3
"""Keeps the copies of the agent files that the app embeds in Kotlin identical to the files in this repository.

  .agents/scripts/security_gate.py      -> AntigravityHermesScripts.SECURITY_GATE_PY
  .agents/scripts/hermes_init.py        -> AntigravityHermesScripts.HERMES_INIT_PY
  .agents/scripts/permission-hook.sh    -> ClaudeWorkspaceFiles.PERMISSION_HOOK_SH   (generated file)
  .claude/agents/*.md                   -> ClaudeWorkspaceFiles.AGENTS               (generated file)

  python3 scripts/embed-agent-files.py --write   regenerate the Kotlin
  python3 scripts/embed-agent-files.py --check   exit 1 when a Kotlin copy is out of date
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
RUNTIME = ROOT / "app/src/main/java/com/nextcraft/forge/runtime"
HERMES_KT = RUNTIME / "AntigravityHermesScripts.kt"
CLAUDE_KT = RUNTIME / "ClaudeWorkspaceFiles.kt"


def raw(text: str) -> str:
    """A Kotlin raw-string body: `$` and triple quotes are escaped, and the file's single trailing newline comes from `+ "\\n"`."""
    if not text.endswith("\n") or text.endswith("\n\n"):
        sys.exit("embedded files must end with exactly one newline")
    # `$` would start a template; a run of three quotes (a Python docstring) would end the raw string.
    return text[:-1].replace("$", "${'$'}").replace('"""', '""${\'"\'}')


def block(name: str, text: str) -> str:
    return f'    val {name}: String = """\n{raw(text)}\n""".trimIndent() + "\\n"'


def replace_block(source: str, name: str, text: str) -> str:
    pattern = re.compile(r'    val ' + name + r': String = """\n.*?\n""".trimIndent\(\) \+ "\\n"', re.S)
    if not pattern.search(source):
        sys.exit(f"{name} not found in {HERMES_KT.name}")
    return pattern.sub(lambda _: block(name, text), source, count=1)


def hermes() -> str:
    source = HERMES_KT.read_text(encoding="utf-8")
    for name, rel in (("SECURITY_GATE_PY", ".agents/scripts/security_gate.py"), ("HERMES_INIT_PY", ".agents/scripts/hermes_init.py")):
        source = replace_block(source, name, (ROOT / rel).read_text(encoding="utf-8"))
    return source


def claude() -> str:
    agents = sorted((ROOT / ".claude/agents").glob("*.md"))
    entries = []
    for path in agents:
        entries.append(f'        "{path.stem}" to """\n{raw(path.read_text(encoding="utf-8"))}\n""".trimIndent() + "\\n",')
    return (
        "package com.nextcraft.forge.runtime\n\n"
        "// Generated by scripts/embed-agent-files.py from .agents/scripts/permission-hook.sh and .claude/agents/*.md. Do not edit.\n\n"
        "/** Claude Code files that the app provisions: the permission hook and the five subagent personas. */\n"
        "internal object ClaudeWorkspaceFiles {\n"
        + block("PERMISSION_HOOK_SH", (ROOT / ".agents/scripts/permission-hook.sh").read_text(encoding="utf-8"))
        + "\n\n    val AGENTS: Map<String, String> = linkedMapOf(\n"
        + "\n".join(entries)
        + "\n    )\n}\n"
    )


def main() -> None:
    mode = sys.argv[1] if len(sys.argv) > 1 else "--check"
    wanted = {HERMES_KT: hermes(), CLAUDE_KT: claude()}
    stale = [p for p, text in wanted.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if mode == "--write":
        for path in stale:
            path.write_text(wanted[path], encoding="utf-8")
            print("updated", path.relative_to(ROOT))
        if not stale:
            print("already up to date")
    elif stale:
        print("out of date (run scripts/embed-agent-files.py --write):", *[str(p.relative_to(ROOT)) for p in stale])
        sys.exit(1)
    else:
        print("embedded copies match the repository files")


if __name__ == "__main__":
    main()
